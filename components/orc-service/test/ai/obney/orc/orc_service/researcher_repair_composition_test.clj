(ns ai.obney.orc.orc-service.researcher-repair-composition-test
  (:require [clojure.test :refer [deftest is]]
            [clojure.java.io :as io] [clojure.string :as str]
            [ai.obney.orc.orc-service.researcher-repair-composition-worker :as c]))
(deftest actual-researcher-child-callable-and-late-semantic-recover-together
  (let [dir (.toFile (java.nio.file.Files/createTempDirectory
                       "orc-researcher-composition-"
                       (make-array java.nio.file.attribute.FileAttribute 0)))
        _ (println :RESEARCHER-COMPOSITION-DIRECTORY (str dir))
        _ (c/run! dir)
        r (c/read! (io/file dir "recovered.edn"))
        p (c/read! (io/file dir "pending.edn"))
        m (c/read! (io/file dir "manifest.edn"))
        wire (c/read! (io/file dir "wire.edn"))
        all (:events r) before (:events p)
        events #(filterv (fn [e] (= % (:event/type e))) all)
        child-id (get-in p [:identity :tick-id]) node-id (get-in p [:identity :node-id])
        child-starts (filterv #(= child-id (:tick-id %)) (events :sheet/tree-tick-started))
        original-start (first (filter #(= node-id (:node-id %)) (events :sheet/node-execution-started)))
        pending-starts (filterv #(= node-id (:node-id %)) (events :sheet/node-execution-started))
        prefix-node (first (filter #(= [:prefix] (:writes %)) (vals (get-in p [:child :nodes-by-id]))))
        prefix-completions (filterv #(= (:id prefix-node) (:node-id %)) (events :sheet/node-execution-completed))
        auth (events :sheet/emitted-model-work-authorized) a (first auth)
        frontier (first (filter #(= (:parent-frontier-id a) (:event/id %)) all))
        claim (first (filter #(= (:generated-claim-id a) (:event/id %)) all))
        parent-start (first (filter #(= (:parent-node-start-id a) (:event/id %)) all))
        semantic-start (first (filter #(= (:node-start-id a) (:event/id %)) all))
        semantic-completion (first (filter #(= (:node-id a) (get-in % [:event :node-id])) (:canonical-completions r)))
        frontiers (events :rlm/researcher-frontier-claimed)
        reservations (events :sheet/provider-call-reserved)
        actionlog (events :rlm/researcher-action-completed)
        index (zipmap (map :event/id all) (range))
        prep-process (c/read! (io/file dir "prepare-process.edn"))
        rec-process (c/read! (io/file dir "recover-process.edn"))]
    (is (:settled r))
    (is (= :success (get-in r [:tick :root-status])))
    (is (= {:count 14 :enabled false :note nil} (:answer (first (:writes r)))))
    (is (empty? (:second-resume r)))
    (is (false? (:callable-before? r)))
    (is (not= (:pid prep-process) (:pid rec-process)))
    (is (= ["fixture/research" "fixture/semantic" "fixture/research"] (mapv #(get-in % [:request :model]) wire)))
    (is (str/includes? (get-in wire [1 :request :messages 0 :content]) "doubled: 14"))
    (is (str/includes? (get-in wire [2 :request :messages 0 :content]) (str "child tick: " child-id)))
    (is (str/includes? (get-in wire [2 :request :messages 0 :content]) ":packet = {:keys [:count :enabled :note]"))
    (is (= 3 (count reservations)))
    (is (= 1 (count child-starts)))
    (is (= (:tick m) (:parent-tick-id (first child-starts))))
    (is (= 1 (count prefix-completions)))
    (is (= :success (:status (first prefix-completions))))
    (is (= 1 (count (str/split-lines (slurp (io/file dir "effects.edn"))))))
    (is (= 2 (count pending-starts)))
    (is (= (:event/id original-start) (:resumed-from-event-id (last pending-starts))))
    (is (= (get-in p [:child :nodes-by-id node-id :fn]) (get-in r [:child :nodes-by-id node-id :fn])))
    (is (= (get-in p [:child :nodes-by-id node-id :recoverable-fn]) (get-in r [:child :nodes-by-id node-id :recoverable-fn])))
    (is (string? (get-in r [:child :nodes-by-id node-id :recoverable-fn :source])))
    (is (= (get-in p [:child :options]) (get-in r [:child :options])))
    (is (= (:deadline m) (get-in r [:parent :options :execution-deadline-ms])))
    (is (= 3 (get-in r [:parent :options :llm-call-budget])))
    (is (= 1 (count (set (map :campaign-deadline-ms frontiers)))))
    (is (= (map :event/id before) (map :event/id (take (count before) all))))
    (is (not-any? #(= :sheet/tree-tick-completed (:event/type %)) before))
    (is (= 1 (count auth)))
    (is (= 2 (:ownership-epoch a)))
    (is (= 2 (:researcher-ownership-epoch parent-start)))
    (is (= 2 (:ownership-epoch frontier)))
    (is (= :generated-child (:kind claim)))
    (is (= (:generated-action-id a) (:logical-action-identity claim)))
    (is (= 2 (:ownership-epoch claim)))
    (is (nil? (:resumed-from-event-id semantic-start)))
    (is (< (index (:event/id parent-start)) (index (:event/id frontier)) (index (:event/id a))))
    (is (< (index (:event/id claim)) (index (:event/id a))))
    (is (= :success (get-in semantic-completion [:event :status])))
    (is (= {:reasoning "controlled semantic packet" :packet {:count 14 :enabled false :note nil}} (:writes semantic-completion)))
    (is (= 3 (count actionlog)))
    (is (= [:provider :phase2 :provider] (mapv :action-kind actionlog)))
    (is (= c/first-code (get-in r [:writes 0 :iterations 0 :code])))
    (is (= c/final-code (get-in r [:writes 0 :iterations 1 :code])))
    (is (= (c/read! (io/file dir "prepare-sources.edn")) (c/read! (io/file dir "recover-sources.edn"))))
    (is (= 0 (:exit (c/read! (io/file dir "recover-exit.edn")))))
    (is (not (.isPresent (java.lang.ProcessHandle/of (:pid prep-process)))))
    (is (not (.isPresent (java.lang.ProcessHandle/of (:pid rec-process)))))
    ))
